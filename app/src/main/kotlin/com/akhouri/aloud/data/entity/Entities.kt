package com.akhouri.aloud.data.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Fts4
import androidx.room.FtsOptions
import androidx.room.Index
import androidx.room.PrimaryKey

enum class BookFormat { EPUB, PDF, TXT, UNKNOWN }

/**
 * How far an import has got. A book is only readable once it reaches [READY]; everything else is
 * shown in the library with its state so a failed import is never silently an empty book.
 */
enum class ImportState { PENDING, IMPORTING, READY, FAILED }

@Entity(tableName = "books")
data class BookEntity(
  @PrimaryKey val id: String,
  /** The SAF document URI we hold a persisted read permission for. */
  val uri: String,
  val title: String,
  val author: String? = null,
  val format: BookFormat = BookFormat.UNKNOWN,
  val language: String? = null,
  /** Absolute path of the cover we extracted into app storage, if the book had one. */
  val coverPath: String? = null,
  val chapterCount: Int = 0,
  val paragraphCount: Int = 0,
  val importedAt: Long = 0L,
  val lastOpenedAt: Long? = null,
  val importState: ImportState = ImportState.PENDING,
  val importError: String? = null,
  /** SHA-256 of the source file, so the same book is recognised wherever it is picked from. */
  val contentHash: String? = null,
  /** The collection this book is filed under, if any. Membership only; nothing is copied. */
  val collectionId: Long? = null,
  /** Play order within the collection. */
  @ColumnInfo(defaultValue = "0") val collectionPosition: Int = 0,
)

/**
 * A named group of books that plays through like one anthology. It holds no content of its
 * own, so grouping books costs no storage.
 */
@Entity(tableName = "collections")
data class CollectionEntity(
  @PrimaryKey(autoGenerate = true) val id: Long = 0L,
  val name: String,
  val createdAt: Long = 0L,
)

@Entity(
  tableName = "chapters",
  indices = [Index(value = ["bookId", "chapterIndex"], unique = true)],
  foreignKeys = [
    ForeignKey(
      entity = BookEntity::class,
      parentColumns = ["id"],
      childColumns = ["bookId"],
      onDelete = ForeignKey.CASCADE,
    ),
  ],
)
data class ChapterEntity(
  @PrimaryKey(autoGenerate = true) val id: Long = 0L,
  val bookId: String,
  /** Position in reading order, zero based. */
  val chapterIndex: Int,
  val title: String? = null,
  /** Index of this chapter's first paragraph in the book-wide paragraph sequence. */
  val startParagraph: Int,
  val paragraphCount: Int,
)

/**
 * One paragraph of normalised text. Every format collapses to this at import, so nothing
 * downstream — reader, search or narration — needs to know whether a book began as EPUB, PDF or
 * plain text.
 *
 * The autogenerated [rowId] is the INTEGER PRIMARY KEY that the external-content FTS table in
 * [ParagraphFts] indexes against.
 */
@Entity(
  tableName = "paragraphs",
  indices = [Index(value = ["bookId", "paragraphIndex"], unique = true)],
  foreignKeys = [
    ForeignKey(
      entity = BookEntity::class,
      parentColumns = ["id"],
      childColumns = ["bookId"],
      onDelete = ForeignKey.CASCADE,
    ),
  ],
)
data class ParagraphEntity(
  @PrimaryKey(autoGenerate = true) val rowId: Long = 0L,
  val bookId: String,
  /** Position in the book-wide paragraph sequence, zero based. */
  val paragraphIndex: Int,
  val chapterIndex: Int,
  /** Source page, for formats that have pages. Null otherwise. */
  val page: Int? = null,
  val text: String,
)

/**
 * External-content FTS mirror of [ParagraphEntity.text]. Room generates the triggers that keep it
 * in step, so searching never needs the book in memory.
 */
@Fts4(
  contentEntity = ParagraphEntity::class,
  tokenizer = FtsOptions.TOKENIZER_UNICODE61,
)
@Entity(tableName = "paragraphs_fts")
data class ParagraphFts(val text: String)

@Entity(
  tableName = "progress",
  foreignKeys = [
    ForeignKey(
      entity = BookEntity::class,
      parentColumns = ["id"],
      childColumns = ["bookId"],
      onDelete = ForeignKey.CASCADE,
    ),
  ],
)
data class ProgressEntity(
  @PrimaryKey val bookId: String,
  val paragraphIndex: Int,
  /** Character offset into that paragraph, so resuming lands mid-paragraph where it left off. */
  val charOffset: Int = 0,
  val updatedAt: Long = 0L,
)

@Entity(
  tableName = "bookmarks",
  indices = [Index("bookId")],
  foreignKeys = [
    ForeignKey(
      entity = BookEntity::class,
      parentColumns = ["id"],
      childColumns = ["bookId"],
      onDelete = ForeignKey.CASCADE,
    ),
  ],
)
data class BookmarkEntity(
  @PrimaryKey(autoGenerate = true) val id: Long = 0L,
  val bookId: String,
  val paragraphIndex: Int,
  val charOffset: Int = 0,
  val title: String? = null,
  val note: String? = null,
  val createdAt: Long = 0L,
)

@Entity(tableName = "search_history")
data class SearchHistoryEntity(
  @PrimaryKey val query: String,
  val bookId: String?,
  val searchedAt: Long,
)
